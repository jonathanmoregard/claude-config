#!/usr/bin/env bash
# Off-machine backup for the proposals sink: commit what the sink holds, scan
# it for secrets, and push it to its private remote.
#
# The mirror image of scripts/claude-pull.sh — same state records, same alert
# debounce, same "never resolve anything by force" posture, opposite direction.
# Read that file first; this one only explains where it differs.
#
# WHY "COMMIT WHATEVER IS THERE" IS RIGHT HERE AND WRONG NEXT DOOR.
# On 2026-08-31 the ~/.claude auto-committer was deleted on purpose (see the
# crontab block in nixos-config home/jonathan-linux.nix): ~/.claude's working
# tree IS the running configuration, so an unattended writer there commits
# half-finished edits into the config the harness is reading, and every session
# afterwards inherits them. The sink is the exact opposite kind of repo. It is
# a store, not a program: nothing reads it to decide behaviour, every byte in it
# was written by a machine as a finished artefact, and the only thing that can
# go wrong by committing it is that a proposal gets versioned slightly early.
# The two scripts look identical and are not — do not "unify" them.
#
# WHAT THIS REFUSES TO DO, ALWAYS.
# No force push. No history rewrite. No `reset --hard`, no `rebase`, no `pull`.
# If the remote holds something this checkout does not, that is a fact about the
# world for a human to reconcile, and every automated resolution of it is a way
# of deleting someone's work. It reports and stops.
#
# THE LEAK GATE IS THE POINT.
# Proposals are generated by a model reading session transcripts, so a proposal
# can quote a credential that was on screen. This process is unattended and its
# destination is GitHub. So: no scan, no push — and the scan runs twice, once
# over what is about to be committed and once over what is about to be pushed,
# because those are different sets. The first keeps a secret out of history at
# all; the second catches commits made by push-proposals.sh, by a session, or by
# a hand that used --no-verify.
#
# There is a global gitleaks pre-commit hook on this host
# (~/.config/git/hooks/pre-commit, home/jonathan.nix). This script does NOT rely
# on it: core.hooksPath is ambient user configuration that any repo-local
# setting overrides and any `--no-verify` skips, and the guarantee has to belong
# to the unit rather than to the machine's current mood. There is deliberately
# no environment variable that turns the scan off.
#
# HOW IT COMPOSES WITH push-proposals.sh.
# push-proposals.sh runs the intake gate and commits; its push now delegates
# here, so there is exactly ONE pusher and therefore exactly one leak gate. They
# cannot deadlock: the gate takes ~/.local/state/proposal-intake-gate/gate.lock
# and releases it when the gate subprocess exits, before push-proposals.sh
# reaches the delegation. They cannot double-commit: whichever runs first leaves
# a clean tree, and the other stages nothing.
#
# Run from a systemd user timer (see nixos-config home/claude-services.nix);
# stdout/stderr land in the journal:
#   journalctl --user -u claude-proposals-push

set -euo pipefail

CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
RSI_CONFIG="$CLAUDE_HOME/recursive-self-improvement/config/config.json"
SINK_DEFAULT="$HOME/.local/state/claude-proposals"

# Single source of truth for the sink path: config.json -> proposals.folder,
# falling back to the canonical literal. Resolved DIRECTLY, never by walking the
# ~/.claude compatibility symlinks — those exist for readers, and a writer that
# depends on a symlink existing is a writer that fails silently on a machine
# where it does not. Same resolution push-proposals.sh and the intake gate use.
resolve_sink() {
  python3 -S -E - "$RSI_CONFIG" "$SINK_DEFAULT" <<'PY' 2>/dev/null || printf '%s\n' "$SINK_DEFAULT"
import json
import os
import sys

fallback = sys.argv[2]
try:
    with open(sys.argv[1], encoding="utf-8") as fh:
        value = json.load(fh).get("proposals", {}).get("folder") or fallback
except Exception:                                             # noqa: BLE001
    value = fallback
value = os.path.expanduser(str(value))
print(value if os.path.isabs(value) else fallback)
PY
}
SINK="${CLAUDE_PROPOSALS_SINK:-$(resolve_sink)}"
case "$SINK" in /*) ;; *) SINK="$PWD/$SINK" ;; esac
SINK="${SINK%/}"

# THE SAME state root, slug scheme and record shape as claude-pull.sh, on
# purpose. hooks/claude-pull-health.py reads every record under this root at
# SessionStart; a second store would mean a second health channel for one class
# of failure, which is its own bug. The `direction` field is what tells the
# reader which way this repo is meant to move.
STATE_ROOT="${CLAUDE_PULL_STATE_ROOT:-${XDG_STATE_HOME:-$HOME/.local/state}/claude-pull}"
STATE="$STATE_ROOT/${SINK//\//%}"
mkdir -p "$STATE"

# The lock the proposal intake gate already takes (scripts/proposal-intake-gate.py,
# GATE_LOCK_PATH). Cooperating with it rather than inventing a second scheme is
# the whole reason this is not a lock of our own: the gate rewrites proposal
# frontmatter in place, and a commit landing mid-annotation would version a
# half-written file.
GATE_LOCK="${CLAUDE_PROPOSALS_GATE_LOCK:-${XDG_STATE_HOME:-$HOME/.local/state}/proposal-intake-gate/gate.lock}"
# Bounded, then give up. A gating run can legitimately take ten minutes (the
# scorer's own timeout is 600s), so waiting it out would blow the unit's
# TimeoutStartSec and wedge the timer. Skipping costs one cycle.
LOCK_WAIT="${CLAUDE_PROPOSALS_LOCK_WAIT:-30}"

log() { printf '%s claude-proposals-push: %s\n' "$(date -Is)" "$*"; }

json_escape() {
  local s="$1"
  s="${s//\\/\\\\}"
  s="${s//\"/\\\"}"
  s="${s//$'\n'/\\n}"
  s="${s//$'\r'/\\r}"
  s="${s//$'\t'/\\t}"
  printf '%s' "$s" | tr -d '\000-\010\013\014\016-\037'
}

# Three states, same meanings as claude-pull.sh's. `unverified` is the middle
# one and the load-bearing one: a tick that could not reach origin did not
# establish anything, and recording `ok` there would be exactly the lie this
# channel exists to prevent. A tick skipped for lock contention writes NOTHING
# and leaves the last real verdict standing.
write_status() { # write_status <ok|unverified|alert> [reason]
  local state="$1" reason="${2:-}" now last_ok tmp
  now="$(date +%s)"
  last_ok="$(cat "$STATE/last-ok-epoch" 2>/dev/null || true)"
  case "$last_ok" in ''|*[!0-9]*) last_ok=0 ;; esac
  if [ "$state" = ok ]; then
    last_ok="$now"
    printf '%s' "$now" > "$STATE/last-ok-epoch"
  fi
  tmp="$STATE/.status.json.$$"
  printf '{"repo":"%s","direction":"push","state":"%s","reason":"%s","checked_at_epoch":%s,"checked_at":"%s","last_ok_epoch":%s}\n' \
    "$(json_escape "$SINK")" "$state" "$(json_escape "$reason")" \
    "$now" "$(date -Is -d "@$now")" "$last_ok" > "$tmp"
  # rename(2), so a reader never sees a half-written verdict.
  mv -f "$tmp" "$STATE/status.json"
}

# The status record is the channel that reaches a Claude session; the toast is
# the one that reaches Jonathan. Both, never only the second — a background
# pusher that stops silently is invisible until someone notices the backup is
# months old. The record is written on every tick; the debounce is a property of
# the toast alone.
alert() {
  local reason="$1"
  log "ALERT: $reason"
  write_status alert "$reason"

  if [ -f "$STATE/last-alert" ] && [ "$(cat "$STATE/last-alert")" = "$reason" ]; then
    return 0
  fi
  printf '%s' "$reason" > "$STATE/last-alert"

  command -v notify-send >/dev/null 2>&1 || {
    log "notify-send not on PATH — alert recorded in journal and status record only"
    return 0
  }
  export DBUS_SESSION_BUS_ADDRESS="${DBUS_SESSION_BUS_ADDRESS:-unix:path=/run/user/$(id -u)/bus}"
  notify-send -u normal "claude-proposals-push needs a hand" \
    "$reason

Sink: $SINK
Log:  journalctl --user -u claude-proposals-push" ||
    log "notify-send failed (no notification daemon?) — alert in journal only"
}

clear_alert() { rm -f "$STATE/last-alert"; write_status ok ""; }

# --------------------------------------------------------------- the sink ----
# Everything above works on a path, not on a repository, so a sink that has been
# deleted or corrupted is still reportable.
if ! cd "$SINK" 2>/dev/null; then
  alert "$SINK cannot be entered — the proposals sink is missing or unreadable, so nothing is being backed up off this machine."
  exit 1
fi

if ! GIT_DIR_PATH="$(git rev-parse --absolute-git-dir 2>/dev/null)"; then
  alert "$SINK is not a git checkout — there is nothing to commit or push, and every proposal written there exists on this disk only."
  exit 1
fi

# The sink must BE a repo, not merely sit inside one. Without this, a sink that
# had lost its .git would resolve to an enclosing repository and `git add -A`
# would stage THAT repository's worktree — the failure cutover-proposals.sh
# documents at length, arriving here by a different road.
SINK_TOP="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [ "$(cd "$SINK_TOP" 2>/dev/null && pwd -P)" != "$(pwd -P)" ]; then
  alert "$SINK is not a git repo of its own — it sits inside the repo rooted at $SINK_TOP. Committing here would stage that repo's whole worktree, so nothing is being pushed."
  exit 1
fi

# ---------------------------------------------------------------- the lock ---
# Opened with <> (O_RDWR, no truncate), never with > — the gate opens the same
# file O_CREAT|O_RDWR for exactly this reason, and truncating a lock file
# another process is holding is how two cooperating schemes stop cooperating.
mkdir -p "$(dirname "$GATE_LOCK")"
exec {lock_fd}<>"$GATE_LOCK"
if ! flock -w "$LOCK_WAIT" "$lock_fd"; then
  # No status write: this tick checked nothing, so it has no verdict to offer,
  # and overwriting the last real one with a guess is what makes a health
  # channel stop carrying information.
  log "the proposal intake gate holds $GATE_LOCK (waited ${LOCK_WAIT}s); skipping this tick"
  exit 0
fi

# --------------------------------------------------------------- the scan ----
# Absolute path from the unit when there is one (a systemd user unit's PATH is
# not the login shell's), otherwise whatever is on PATH. Absent is a hard stop:
# an unattended pusher that cannot scan does not push.
GITLEAKS_BIN="${GITLEAKS:-}"
if [ -z "$GITLEAKS_BIN" ]; then
  GITLEAKS_BIN="$(command -v gitleaks 2>/dev/null || true)"
fi

# Turn a gitleaks JSON report into lines a human can act on. Every field taken
# is a LOCATION — file, rule, line. The secret itself is "REDACTED" in the
# report (that is what --redact does) and is never read out of it here either:
# this text lands in the journal AND in the status record the SessionStart hook
# feeds into a Claude session's context, and a leak gate that pastes the leak
# into two more places has not helped.
summarise_report() { # summarise_report <report path>
  python3 -S -E - "$1" <<'PY' 2>/dev/null || true
import json
import sys

try:
    with open(sys.argv[1], encoding="utf-8") as fh:
        findings = json.load(fh)
except Exception:                                             # noqa: BLE001
    raise SystemExit(0)
if not isinstance(findings, list):
    raise SystemExit(0)
for f in findings[:10]:
    if not isinstance(f, dict):
        continue
    print("  %s:%s — %s" % (f.get("File", "?"), f.get("StartLine", "?"),
                            f.get("RuleID", "?")))
if len(findings) > 10:
    print("  ... and %d more" % (len(findings) - 10))
PY
}

scan() { # scan <human description> <remedy command> <gitleaks args...>
  local what="$1" remedy="$2"; shift 2
  if [ -z "$GITLEAKS_BIN" ]; then
    alert "gitleaks is not available, so $what could not be scanned for secrets — refusing to push. Proposals are written from session transcripts and can quote a credential; an unattended push without a scan is not a trade this unit makes. Install gitleaks (it is in nixos-config home/jonathan.nix) or check this unit's GITLEAKS= path."
    return 1
  fi
  local report rc=0 found
  report="$STATE/.gitleaks-report.$$.json"
  # --redact so a detected secret never reaches the report, the journal, or the
  # status record. --exit-code 1 is the default but stated, because the whole
  # gate rests on it.
  "$GITLEAKS_BIN" git --no-banner --redact --exit-code 1 --log-level error \
    --report-format json --report-path "$report" "$@" "$SINK" >/dev/null 2>&1 || rc=$?
  if [ "$rc" -eq 0 ]; then
    rm -f "$report"
    return 0
  fi
  found="$(summarise_report "$report")"
  rm -f "$report"
  # ANY nonzero exit blocks, not just the leaks-found code. A scanner that
  # crashed, ran out of memory, or was handed arguments it did not understand
  # has told us nothing about the content, and "we learned nothing" must not be
  # spelled the same way as "it is clean". The two cases are distinguishable to
  # the reader by whether findings were listed, which is why the empty case
  # says so rather than printing a blank.
  alert "gitleaks refused $what (exit $rc) — nothing was pushed. Locations (the secrets themselves are redacted):
${found:-  (no findings were reported, so gitleaks itself failed rather than finding something — re-run it by hand)}
Reproduce with: $remedy
Then remove the secret from $SINK, or add a gitleaks allowlist entry for it. Until it is resolved every tick will block here and the sink will not be backed up."
  return 1
}

# ------------------------------------------------------------- the commit ----
# `git add -A` from the sink root: additions, gate annotations, drained status
# flips and removals alike. Its own .gitignore keeps the runtime lock out.
git add -A

if ! git diff --cached --quiet; then
  # Scan BEFORE committing, so a secret never enters history at all. Blocking
  # after the commit would leave the leak permanently in the local log with
  # every later tick re-detecting it — fail-closed, but needlessly unrecoverable.
  # The remedy names `dir`, not `--staged`: the index is reset two lines below,
  # so a reader who copies a `--staged` command finds nothing and concludes the
  # alert was spurious. `dir` scans the working tree, which is where the file
  # still is.
  if ! scan "the changes staged in the proposals sink" \
            "$GITLEAKS_BIN dir --redact $SINK" --staged; then
    # MIXED reset — index only, never --hard. The offending file stays exactly
    # where the writer put it, unstaged and uncommitted, for a human to fix.
    git reset -q || true
    exit 1
  fi
  staged_count="$(git diff --cached --name-only | wc -l)"
  git commit -q -m "proposals: $(date +%Y-%m-%d)"
  log "committed $staged_count change(s) in $SINK"
fi

# -------------------------------------------------------------- the remote ---
BRANCH="$(git symbolic-ref --short HEAD 2>/dev/null || true)"
if [ -z "$BRANCH" ]; then
  alert "HEAD is detached in $SINK — auto-push is off until a branch is checked out."
  exit 1
fi

if [ -z "$(git remote)" ]; then
  alert "$SINK has no git remote, so every proposal in it exists on this disk only. Add the private origin (git remote add origin <url>) — this script will not invent one."
  exit 1
fi

if ! UPSTREAM="$(git rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null)"; then
  alert "Branch '$BRANCH' in $SINK has no upstream, so nothing is being pushed. Set one with: git -C $SINK push -u origin $BRANCH"
  exit 1
fi
REMOTE="${UPSTREAM%%/*}"

# Bound the network op. A stalled connection must not wedge the run while it
# holds the lock the intake gate is waiting on.
export GIT_SSH_COMMAND="ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new -o ConnectTimeout=15 -o ServerAliveInterval=15 -o ServerAliveCountMax=4"

if ! timeout 60 git fetch --quiet --prune "$REMOTE" "$BRANCH"; then
  # A laptop is offline often enough that one failed fetch is noise; a run of
  # them means something is actually broken. Below the threshold it is still
  # emphatically not a clean bill of health — the tick never learned what origin
  # holds — so the record says `unverified` rather than `ok`.
  fails=$(( $(cat "$STATE/fetch-failures" 2>/dev/null || echo 0) + 1 ))
  printf '%s' "$fails" > "$STATE/fetch-failures"
  log "fetch failed or timed out (60s) — consecutive failures: $fails"
  if [ "$fails" -ge 6 ]; then
    alert "git fetch has failed $fails times in a row for $SINK — check network, SSH key, or the origin remote. Proposals written since the last successful push exist on this disk only."
  else
    write_status unverified "git fetch failed $fails time(s) in a row; it is unknown whether the proposals sink has been pushed since the last successful tick."
  fi
  exit 1
fi
rm -f "$STATE/fetch-failures"

local_sha="$(git rev-parse HEAD)"
remote_sha="$(git rev-parse "$UPSTREAM")"
base_sha="$(git merge-base HEAD "$UPSTREAM")"

if [ "$local_sha" = "$remote_sha" ]; then
  clear_alert
  exit 0
fi

if [ "$local_sha" = "$base_sha" ]; then
  # Strictly behind. Nothing else writes this repo, so this means someone
  # pushed from elsewhere — reconciling it is a pull, and pulling is not this
  # script's job any more than force-pushing over it is.
  alert "$UPSTREAM is $(git rev-list --count "HEAD..$UPSTREAM") commit(s) ahead of this checkout of $SINK, which has nothing of its own to push. Auto-push will not merge, rebase or reset for you — bring the checkout up by hand (git -C $SINK pull --ff-only)."
  exit 1
fi

if [ "$remote_sha" != "$base_sha" ]; then
  alert "$BRANCH and $UPSTREAM have diverged for $SINK ($(git rev-list --count "$UPSTREAM..HEAD") local / $(git rev-list --count "HEAD..$UPSTREAM") remote commits). Auto-push will never force over that — resolve it by hand."
  exit 1
fi

# --------------------------------------------------------------- the push ----
ahead="$(git rev-list --count "$UPSTREAM..HEAD")"

# The second scan, over exactly the commits this push would ship. The staged
# scan above cannot cover them: push-proposals.sh commits without pushing, a
# session commits by hand, and `--no-verify` skips the global pre-commit hook.
if ! scan "the $ahead commit(s) this push would ship" \
          "$GITLEAKS_BIN git --redact --log-opts '$UPSTREAM..HEAD' $SINK" \
          --log-opts "$UPSTREAM..HEAD"; then
  exit 1
fi

# Explicit refspec, no --force, no --force-with-lease, no lease at all. The
# only push this script is willing to make is a fast-forward of one branch onto
# its own upstream, and the divergence check above is what establishes that.
if ! push_err="$(timeout 120 git push "$REMOTE" "$BRANCH:$BRANCH" 2>&1)"; then
  alert "git push failed for $SINK ($ahead commit(s) waiting):
$(printf '%s' "$push_err" | head -5)"
  exit 1
fi

log "pushed $ahead commit(s) to $UPSTREAM ($(git rev-parse --short "$base_sha") -> $(git rev-parse --short HEAD))"
clear_alert
