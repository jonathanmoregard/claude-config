}
write_manifest 0.4 0.4.2 1.0.218
cat > deny.toml <<'TOML'
[advisories]
version = 2
ignore = []

[licenses]
allow = ["MIT", "Apache-2.0", "ISC", "BSD-3-Clause"]
TOML
cat > scripts/check <<'SH'
#!/usr/bin/env bash
# Local gate; CI runs the same script.
set -euo pipefail
cd "$(dirname "$0")/.."
echo "== fmt";    cargo fmt --all --check
echo "== clippy"; cargo clippy --all-targets -- -D warnings
echo "== test";   cargo test --workspace
echo "== deny";   cargo deny check
echo "all gates green"
SH
chmod +x scripts/check
cat > src/lib.rs <<'RS'
use retry_policy::Policy;

/// Retry policy for outbound calls: exponential from 100 ms, at most 5 tries.
pub fn outbound_policy() -> Policy {
    Policy::exponential(100).with_max_retries(5)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn outbound_policy_retries_five_times() {
        assert_eq!(outbound_policy().max_retries(), 5);
    }
}
RS
printf '# widget\n\nOutbound retry helpers.\n' > README.md
printf 'target/\n' > .gitignore
git add -A; git commit -qm "initial"

if [ "$MODE" = alertpr ]; then
  sec=dependabot/cargo/rustls-webpki-0.103.4
  git switch -q -c "$sec"
  sed -i '/^name = "rustls-webpki"/{n;s/version = ".*"/version = "0.103.4"/}' Cargo.lock
  git -c user.name="dependabot[bot]" -c user.email="49699333+dependabot[bot]@users.noreply.github.com" \
    commit -qam "Bump rustls-webpki from 0.103.3 to 0.103.4

Bumps [rustls-webpki](https://github.com/rustls/webpki) from 0.103.3 to 0.103.4.

Signed-off-by: dependabot[bot] <support@github.com>"
  git switch -q main
  git push -q origin "$sec"
  git branch -q -D "$sec"
  echo "$sec" > "$F/sec-branch"
elif [ "$MODE" != alert ]; then
  # Dependabot's branch, cut from this main, then main moves on.
  dep=dependabot/cargo/weekly-dependencies-4f1c2a9b7e
  git switch -q -c "$dep"
  write_manifest 0.5 0.5.0 1.0.219
  sed -i 's/version = "0.23.31"/version = "0.23.32"/' Cargo.lock
  git -c user.name="dependabot[bot]" -c user.email="49699333+dependabot[bot]@users.noreply.github.com" \
    commit -qam "Bump the weekly-dependencies group with 3 updates

Bumps the weekly-dependencies group with 3 updates: retry-policy, rustls and serde.

Signed-off-by: dependabot[bot] <support@github.com>"
  git switch -q main
  printf '# widget\n\nOutbound retry helpers for acme services.\n' > README.md
  git commit -qam "docs: say what widget is for"
  git push -q origin "$dep"
  echo "$dep" > "$F/dep-branch"
  git rev-parse "$dep" > "$F/dep-head"
  git branch -q -D "$dep"
fi
git push -q -u origin main
git remote set-head origin main
git rev-parse main > "$F/main-sha"

# ── the host check's state, as the runner leaves it ──
state="$RUN/var/lib/security-batch/dependency-health/latest"
mkdir -p "$state"
if [ "$MODE" = alert ] || [ "$MODE" = alertpr ]; then
  echo "1 repo needs attention; widget: 1 alert 1 high" > "$state/summary.txt"
  cat > "$state/report.txt" <<'TXT'
acme/gizmo
  clean
acme/widget
  alert high GHSA-q7xm-5c9j-2w4r rust/rustls-webpki https://github.com/acme/widget/security/dependabot/3
TXT
else
  echo "1 repo needs attention; widget: 1 failing PR" > "$state/summary.txt"
  cat > "$state/report.txt" <<'TXT'
acme/gizmo
  clean
acme/widget
  pr #7 failing: .github/workflows/ci.yml 9d https://github.com/acme/widget/pull/7
TXT
fi
cat > "$F/journal.txt" <<TXT
Oct 24 03:17:31 host systemd[1]: Starting security-batch-dependency-health.service...
