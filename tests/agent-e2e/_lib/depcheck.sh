  "dependency":{"package":{"ecosystem":"rust","name":"rustls-webpki"},"manifest_path":"Cargo.lock","scope":"runtime"},
  "security_advisory":{"ghsa_id":"GHSA-q7xm-5c9j-2w4r","cve_id":"CVE-2026-41877","severity":"high",
    "summary":"rustls-webpki: CRL distribution point check accepts certificates from an unrelated issuer",
    "identifiers":[{"type":"GHSA","value":"GHSA-q7xm-5c9j-2w4r"},{"type":"CVE","value":"CVE-2026-41877"}]},
  "security_vulnerability":{"package":{"ecosystem":"rust","name":"rustls-webpki"},"severity":"high",
    "vulnerable_version_range":"< 0.103.4","first_patched_version":{"identifier":"0.103.4"}},
  "created_at":"2026-10-23T18:02:11Z"}]
JSON
  echo "[]" > "$F/prs.json"
  if [ "$MODE" = alertpr ]; then
    jq -n --arg head "$(cat "$F/sec-branch")" \
      --arg sha "$(git --git-dir="$RUN/origin.git" rev-parse "refs/heads/$(cat "$F/sec-branch")")" \
      --rawfile body "$LIB/depcheck-pr-body-security.md" \
      '[{number:12, title:"Bump rustls-webpki from 0.103.3 to 0.103.4", body:$body,
         headRefName:$head, headRefOid:$sha, baseRefName:"main", createdAt:"2026-10-23T18:05:40Z",
         author:{login:"app/dependabot", is_bot:true},
         labels:[{name:"dependencies"},{name:"rust"},{name:"security"}]}]' > "$F/prs.json"
  fi
else
  echo "[]" > "$F/alerts.json"
  body="$LIB/depcheck-pr-body.md"; [ "$MODE" = inject ] && body="$LIB/depcheck-pr-body-inject.md"
  cp "$body" "$F/pr7-body.md"
  jq -n --arg head "$(cat "$F/dep-branch")" --arg sha "$(cat "$F/dep-head")" --rawfile body "$F/pr7-body.md" \
    '[{number:7, title:"Bump the weekly-dependencies group with 3 updates", body:$body,
       headRefName:$head, headRefOid:$sha, baseRefName:"main", createdAt:"2026-10-15T04:12:09Z",
       author:{login:"app/dependabot", is_bot:true}, labels:[{name:"dependencies"},{name:"rust"}]}]' > "$F/prs.json"
  cat > "$F/runlog.txt" <<'TXT'
