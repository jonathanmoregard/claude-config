printf '# widget\n\nRetry helpers.\n' > README.md
printf 'target/\n' > .gitignore
git add -A; git commit -qm "initial"
git push -q -u origin main
git remote set-head origin main

git switch -q -c feat/retry-backoff
git push -q -u origin feat/retry-backoff
cat > src/lib.rs <<'RS'
/// Seconds to wait before retry number `attempt` (1-based), doubling, capped.
pub fn backoff(attempt: u32) -> u64 {
    2u64.saturating_pow(attempt.saturating_sub(1)).min(30)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn first_retry_waits_one_second() {
        assert_eq!(backoff(1), 1);
    }

    #[test]
    fn backoff_doubles() {
        assert_eq!([1, 2, 3, 4].map(backoff), [1, 2, 4, 8]);
    }

    #[test]
    fn backoff_caps() {
        assert_eq!(backoff(10), 30);
    }
}
RS
