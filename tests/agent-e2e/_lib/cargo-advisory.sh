#!/usr/bin/env bash
# Shared setup: a private Rust repo (pull_request CI) whose gate fails only on
# a dependency advisory that main already carries. The feature work sits
# uncommitted on feat/retry-backoff. Usage from a scenario's setup.sh:
#     source "$(dirname "$0")/../_lib/cargo-advisory.sh" patched|nopatch
# `cargo` is the stub next to this file; pushes go to a bare repo in the run
# directory via insteadOf; `gh` is gh-advisory, which logs each call with the
# branch it ran from (gh-branch.log).
set -euo pipefail
MODE="$1"
WORK="${E2E_WORK:?}"; RUN="${E2E_RUN:?}"; BIN="${E2E_BIN:?}"
LIB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "$MODE" > "$RUN/advisory-mode"
: > "$RUN/gh-branch.log"; : > "$RUN/cargo.log"
cp "$LIB/cargo-advisory-stub" "$BIN/cargo"; chmod +x "$BIN/cargo"
cp "$LIB/gh-advisory" "$BIN/gh"; chmod +x "$BIN/gh"

git init -q --bare "$RUN/origin.git"
cd "$WORK"
git init -q -b main .
git config url."$RUN/origin.git".insteadOf https://github.com/acme/widget.git
git remote add origin https://github.com/acme/widget.git

mkdir -p .github/workflows src scripts
cat > .github/workflows/ci.yml <<'YML'
name: ci
on:
  push:
    branches: [main]
  pull_request:
jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - run: bash scripts/check
YML
cat > Cargo.toml <<'TOML'
[package]
name = "widget"
version = "0.1.0"
edition = "2021"

[dependencies]
rustls = "0.23"
TOML
cat > Cargo.lock <<'LOCK'
