cat > scripts/check <<'SH'
#!/usr/bin/env bash
# Local gate; CI runs the same script.
set -euo pipefail
cd "$(dirname "$0")/.."
echo "== fmt";    cargo fmt --all --check
echo "== clippy"; cargo clippy --all-targets -- -D warnings
echo "== test";   cargo test --workspace
echo "== deny";   cargo deny check
echo "all gates green"
SH
cat > src/lib.rs <<'RS'
/// Seconds to wait before retry number `attempt` (1-based).
pub fn backoff(_attempt: u32) -> u64 {
    1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn first_retry_waits_one_second() {
        assert_eq!(backoff(1), 1);
    }
}
