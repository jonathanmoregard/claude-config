#!/usr/bin/env bash
# Install upstream-merge auto-sync for a fork.
# Idempotent. Detects fork parent via gh api, renders scoped settings,
# generates wrapper, optionally installs cron entry.
#
# Usage:
#   install-upstream-merge.sh --repo PATH [--schedule "CRON_EXPR" | --pin] [--branch NAME]
#
#   --repo       Absolute path to the fork on disk.
#   --schedule   Cron expression (e.g. "0 */6 * * *"). Omit to install as manual-run.
#   --pin        Record current upstream SHA, do not install cron. Re-run to bump.
#   --branch     Merge target branch. Default: parent's default_branch (via gh api).

set -euo pipefail

SKILL_DIR="$(cd "$(dirname "$0")" && pwd)"

REPO=""
SCHEDULE=""
PIN=0
BRANCH=""

while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="$2"; shift 2;;
    --schedule) SCHEDULE="$2"; shift 2;;
    --pin) PIN=1; shift;;
    --branch) BRANCH="$2"; shift 2;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0;;
    *) echo "Unknown arg: $1" >&2; exit 1;;
  esac
done

[ -n "$REPO" ] || { echo "--repo required" >&2; exit 1; }
[ -d "$REPO/.git" ] || { echo "$REPO is not a git repo" >&2; exit 1; }
if [ $PIN -eq 1 ] && [ -n "$SCHEDULE" ]; then
  echo "--pin and --schedule are mutually exclusive" >&2; exit 1
fi

command -v jq   >/dev/null || { echo "jq required" >&2; exit 1; }
command -v gh   >/dev/null || { echo "gh CLI required" >&2; exit 1; }
command -v uv   >/dev/null || { echo "uv required (to run repo-check)" >&2; exit 1; }

REPO_NAME=$(basename "$REPO")
DATA_DIR="$HOME/.claude/repo-autosync-data/$REPO_NAME"

# --- Detect origin + fork parent ---
ORIGIN_URL=$(git -C "$REPO" config --get remote.origin.url)
# Normalize owner/repo from origin (handles https + ssh)
ORIGIN_SLUG=$(echo "$ORIGIN_URL" \
  | sed -E 's#(git@github.com:|https?://github.com/)##' \
  | sed -E 's#\.git$##')

META=$(gh api "repos/$ORIGIN_SLUG" --jq '{fork, parent_url: .parent.clone_url, parent_branch: .parent.default_branch, parent_slug: .parent.full_name}')
IS_FORK=$(echo "$META" | jq -r .fork)
PARENT_URL=$(echo "$META" | jq -r .parent_url)
PARENT_BRANCH=$(echo "$META" | jq -r .parent_branch)
PARENT_SLUG=$(echo "$META" | jq -r .parent_slug)

if [ "$IS_FORK" != "true" ] || [ "$PARENT_URL" = "null" ]; then
  echo "ERROR: $ORIGIN_SLUG is not a fork (or parent missing). Aborting." >&2
  exit 1
fi

echo "Fork confirmed: $ORIGIN_SLUG ← $PARENT_SLUG"

[ -n "$BRANCH" ] || BRANCH="$PARENT_BRANCH"

# --- Ensure upstream remote ---
if ! git -C "$REPO" remote | grep -qx upstream; then
  echo "Adding upstream remote: $PARENT_URL"
  git -C "$REPO" remote add upstream "$PARENT_URL"
else
  EXISTING=$(git -C "$REPO" config --get remote.upstream.url)
  if [ "$EXISTING" != "$PARENT_URL" ]; then
    echo "WARNING: upstream remote exists but points to $EXISTING (expected $PARENT_URL)" >&2
    echo "Leaving as-is. Fix manually if needed." >&2
  fi
fi

git -C "$REPO" fetch upstream >/dev/null 2>&1 || true

# --- Data dir + rendered settings ---
mkdir -p "$DATA_DIR"
: > "$DATA_DIR/last-update.log"

RESOLVE_SETTINGS="$DATA_DIR/upstream-resolve-settings.json"

sed -e "s#{{REPO}}#$REPO#g" -e "s#{{DATA_DIR}}#$DATA_DIR#g" \
  "$SKILL_DIR/upstream-resolve-settings.json.tmpl" > "$RESOLVE_SETTINGS"

# --- config.env ---
LOCAL_BRANCH=$(git -C "$REPO" symbolic-ref --short HEAD 2>/dev/null || echo "$BRANCH")

cat > "$DATA_DIR/config.env" <<EOF
# Generated by install-upstream-merge.sh — edit with care, re-run installer to refresh
export REPO="$REPO"
export UPSTREAM_REMOTE="upstream"
export UPSTREAM_BRANCH="$BRANCH"
export LOCAL_BRANCH="$LOCAL_BRANCH"
export UPSTREAM_URL="$PARENT_URL"
export DATA_DIR="$DATA_DIR"
export RESOLVE_SETTINGS="$RESOLVE_SETTINGS"
export REPO_CHECK_DIR="$HOME/Repos/repo-check"
EOF

# --- wrapper.sh ---
cat > "$DATA_DIR/wrapper.sh" <<EOF
#!/usr/bin/env bash
# Generated. Sources per-repo config and invokes canonical upstream-merge.sh.
set -euo pipefail
source "$DATA_DIR/config.env"
exec "$SKILL_DIR/upstream-merge.sh"
EOF
chmod +x "$DATA_DIR/wrapper.sh"

# --- pin mode ---
if [ $PIN -eq 1 ]; then
  UPSTREAM_SHA=$(git -C "$REPO" rev-parse "upstream/$BRANCH")
  echo "$UPSTREAM_SHA" > "$DATA_DIR/pinned-sha"
  echo "Pinned upstream/$BRANCH at $UPSTREAM_SHA"
  echo "No cron installed. Re-run installer to bump the pin."
  echo "Manual run: $DATA_DIR/wrapper.sh"
  exit 0
fi

# --- cron (schedule mode) ---
if [ -n "$SCHEDULE" ]; then
  TAG="$REPO_NAME-upstream-sync"
  NEW_LINE="$SCHEDULE $DATA_DIR/wrapper.sh >> $DATA_DIR/last-update.log 2>&1 # $TAG"
  # Read existing crontab, strip any prior entry with our tag, append new entry.
  # Use a temp file to avoid subshell/pipefail interactions with grep -v exit=1.
  TMP_CRON=$(mktemp)
  crontab -l 2>/dev/null > "$TMP_CRON" || true
  if grep -q "# $TAG$" "$TMP_CRON" 2>/dev/null; then
    grep -v "# $TAG$" "$TMP_CRON" > "$TMP_CRON.new" || true
    mv "$TMP_CRON.new" "$TMP_CRON"
    MSG="Updated cron entry: $TAG"
  else
    MSG="Installed cron entry: $TAG ($SCHEDULE)"
  fi
  echo "$NEW_LINE" >> "$TMP_CRON"
  crontab - < "$TMP_CRON"
  rm -f "$TMP_CRON"
  echo "$MSG"
else
  echo "No --schedule and no --pin — installed as manual-run only."
  echo "Manual run: $DATA_DIR/wrapper.sh"
fi

echo ""
echo "Setup complete:"
echo "  repo:     $REPO"
echo "  upstream: $PARENT_SLUG ($BRANCH)"
echo "  data:    $DATA_DIR"
echo "  log:     $DATA_DIR/last-update.log"
